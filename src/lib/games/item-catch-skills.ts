/**
 * アイテムキャッチのスキル説明
 * =============================================================
 * 効果の実体は frenchie-catch-game.tsx の LV テーブルと switch 文にある。
 * ここはそれを人が読む形へ書き起こしたものなので、数値を変えたら両方直す。
 *
 * 名前・レアリティ・画像は COLLECTION_ITEMS から id で引くため、ここには持たない。
 * （持たせると図鑑側と食い違ったときに気づけない）
 *
 * 得点倍率について（"○秒間 ×n"系スキル）:
 * 効果中に同じアイテムや他の倍率アイテムを重ねて取っても上書きされず、
 * 重なっている時間だけ全ての倍率が掛け合わされる。
 * 例）5秒間×5のアイテムを取り、3秒後にもう一度同じアイテムを取ると、
 * 　　重複する2秒間だけ ×5 × ×5 = ×25 になり、その後は残りの×5だけが続く。
 * 「食べ物カテゴリ限定 ×n」（二足A）「宝箱連続ボーナス」などの別系統の倍率とも、
 * 有効なタイミングが重なれば同様に掛け合わされる。二足A自体も同じ考え方で、
 * 効果中にもう一度取れば重複区間だけ掛け合わされる。
 *
 * 「次のN個 ×n」系スキル（フリスビー/金の冠ボール/いちごロールケーキ/こもち）は
 * 秒数の代わりに「対象となるキャッチ回数」で管理し、考え方は同じ。
 * 例）「次の2個 ×2」が有効な間にもう一度同じアイテムを取ると、
 * 　　その直後の1個目は ×2 × ×2 = ×4、2個目は先発の効果が切れて ×2 だけになる。
 *
 * なお、段ボール拡大／落下速度アップ／アイテム出現量アップ／マグネットは
 * 得点倍率ではないため対象外。重複取得時は従来どおり「上書き＋延長」のままで、
 * 掛け合わせは行わない。
 */

